"""Script Generator agent: approved cases -> readable pytest + Playwright code.

One explicit test function per case, grouped into files by kind, with the
case, rule and requirement IDs in each docstring. Files are deterministic:
the same cases always produce the same code, so changes are reviewable in git.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from agentqa import language, live
from agentqa.config import Project
from agentqa.store import Store

RUNTIME = Path(__file__).resolve().parent.parent / "runtime"
LIVE_MODULE = Path(__file__).resolve().parent.parent / "live.py"
FILES = {
    "access_denied": "test_access.py", "workflow": "test_workflows.py", "page_smoke": "test_pages.py",
    "links_ok": "test_pages.py", "form_valid": "test_forms.py", "field_rejects": "test_forms.py",
    "field_accepts": "test_forms.py", "field_options": "test_forms.py", "field_attribute": "test_forms.py",
    "a11y_basic": "test_accessibility.py", "api_smoke": "test_api.py", "api_access": "test_api.py",
    "record_isolation": "test_api.py", "security_headers": "test_security.py", "security_session": "test_security.py",
    "security_csrf": "test_security.py", "performance_load": "test_performance.py", "visual_snapshot": "test_visual.py",
    "manual_converted": "test_manual.py", "security_otp": "test_security.py", "functional": "test_functional.py",
}
HEADER = '''"""Generated by AgentQA Studio - do not edit by hand; regenerate with `agentqa generate`.

{what}
"""
import pytest

import agentqa_runtime as rt
'''
WHAT = {
    "test_access.py": "Role-based access control: who must be blocked from which screen.",
    "test_workflows.py": "Multi-role workflows (maker-checker hand-offs).",
    "test_pages.py": "Every screen loads for its roles; every internal link works.",
    "test_forms.py": "Form validation: valid data is accepted, invalid data is rejected by the server.",
    "test_accessibility.py": "Accessibility per screen: WCAG 2.2 AA rules checked by axe-core.",
    "test_api.py": "APIs the screens call: answers, login and role checks, and record isolation between users.",
    "test_security.py": "Security basics: headers, session handling at login and logout, anti-forgery tokens.",
    "test_performance.py": "Short load checks against the response-time limit.",
    "test_visual.py": "Visual snapshots: each screen compared with its approved image.",
    "test_manual.py": "Manual test cases imported from Excel and converted into automated steps.",
    "test_functional.py": "Functional test cases drafted like a manual tester: login, logout, navigation, forms, search.\n"
                          "Values from the Test data page appear as tokens ({mobile}, {password:wrong}) and are filled in at run time.",
}


def _lit(v) -> str:
    return repr(v)


def _body(case: dict) -> list[str]:
    p = dict(case["params"] or {})
    if p.get("field_override"):
        p["field"] = p["field_override"]
    t = case["type"]
    role = case["role"]
    if t == "access_denied":
        return [f"page = as_role({role!r})", f"rt.check_access_denied(page, {case['path']!r}, {role!r})"]
    if t == "page_smoke":
        return [f"page = as_role({role!r})", f"rt.check_page(page, {case['path']!r}, max_load_ms={p.get('max_load_ms')!r})"]
    if t == "links_ok":
        return [f"page = as_role({role!r})", f"rt.check_links(page, {_lit(p['links'])})"]
    if t == "a11y_basic":
        return [f"page = as_role({role!r})", f"rt.check_a11y(page, {case['path']!r})"]
    if t == "workflow":
        return [f"rt.run_workflow(as_role, {_lit(p['steps'])})"]
    if t == "form_valid":
        return [f"page = as_role({role!r})",
                f"rt.check_form_valid(page, {case['path']!r}, form={p['form']!r}, form_id={p.get('form_id') or None!r},",
                f"                    values={_lit(p['values'])})"]
    common = (f"page, {case['path']!r}, form={p['form']!r}, form_id={p.get('form_id') or None!r}, "
              f"field={p['field']!r}, label={p['label']!r}")
    if t in ("field_rejects", "field_accepts"):
        fn = "check_field_rejects" if t == "field_rejects" else "check_field_accepts"
        return [f"page = as_role({role!r})",
                f"rt.{fn}({common},",
                f"    base={_lit(p['base'])},",
                f"    values={_lit(p['values'])},",
                f"    descriptions={_lit(p['descriptions'])})"]
    if t == "field_attribute":
        return [f"page = as_role({role!r})",
                f"rt.check_attribute({common}, attribute={p['attribute']!r}, expected={p['expected']!r})"]
    if t == "field_options":
        return [f"page = as_role({role!r})", f"rt.check_options({common}, expected={_lit(p['expected'])})"]
    raise ValueError(f"Unknown case type {t}")


def _body_new(case: dict) -> list[str] | None:
    p = case["params"] or {}
    t, role, path = case["type"], case["role"], case["path"]
    if t == "api_smoke":
        return [f"page = as_role({role!r})", f"rt.check_api(page, {path!r}, keys={_lit(p.get('keys') or [])}, "
                f"max_ms={p.get('max_ms')!r})"]
    if t == "api_access":
        return [f"page = as_role({role!r})", f"rt.check_api_denied(page, {path!r}, {role!r})"]
    if t == "record_isolation":
        return [f"rt.check_record_isolation(as_role, {path!r}, owner={role!r}, peer={p['peer']!r})"]
    if t == "security_headers":
        return [f"page = as_role({role!r})", f"rt.check_security_headers(page, {path or '/'!r})"]
    if t == "security_session":
        return [f"rt.check_session(as_role, {role!r}, logout_url={p['logout_url']!r}, protected={p['protected']!r})"]
    if t == "security_csrf":
        return [f"rt.check_csrf(as_role, {_lit(p['forms'])})"]
    if t == "security_otp":
        return [f"page = as_role({role!r})", f"rt.check_otp_single_use(page, {p['role']!r})"]
    if t == "performance_load":
        return [f"page = as_role({role!r})",
                f"rt.check_load(page, {path!r}, users={p['users']!r}, seconds={p['seconds']!r}, "
                f"limit_ms={p['limit_ms']!r}, max_error_rate={p['max_error_rate']!r})"]
    if t == "visual_snapshot":
        return [f"page = as_role({role!r})",
                f"rt.check_visual(page, {path!r}, key={p['key']!r}, threshold={p['threshold']!r}, "
                f"mask={_lit(p.get('mask') or [])}, full_page={p.get('full_page', True)!r})"]
    if t == "manual_converted":
        return [f"rt.run_steps(as_role, {role!r}, {_lit(p.get('steps') or [])})"]
    if t == "functional":
        steps = [{k: v for k, v in st.items()} for st in p.get("steps") or []]
        lines = [f"rt.run_steps(as_role, {p.get('page_role') or role!r}, ["]
        lines += [f"    {_lit(st)}," for st in steps]
        return lines + ["])"]
    return None


def _landings(project: Project) -> dict[str, str]:
    """Where each role landed after its last login (from the saved sessions), for tests that must start there."""
    out = {}
    for f in (project.state / "auth").glob("*.session.json"):
        try:
            out[f.name[: -len(".session.json")]] = json.loads(f.read_text(encoding="utf-8")).get("landing") or "/"
        except Exception:  # noqa: BLE001
            continue
    return out


def generate(project: Project, store: Store) -> dict:
    cases = store.all("SELECT * FROM cases WHERE status='approved' ORDER BY seq")
    out = project.tests_dir
    if out.exists():
        for f in out.glob("test_*.py"):
            f.unlink()
    out.mkdir(exist_ok=True)
    shutil.copy(RUNTIME / "agentqa_runtime.py", out / "agentqa_runtime.py")
    shutil.copy(RUNTIME / "conftest.py", out / "conftest.py")
    shutil.copy(LIVE_MODULE, out / "agentqa_live.py")
    if (RUNTIME / "vendor" / "axe.min.js").exists():
        shutil.copy(RUNTIME / "vendor" / "axe.min.js", out / "agentqa_axe.js")
    shutil.copy(RUNTIME / "widgets.js", out / "agentqa_widgets.js")
    from agentqa import inbox
    ex, cfg = project.cfg["execution"], project.cfg
    settings = {"base_url": project.base_url, "login_url": cfg["login"]["url"], "oracles": cfg["oracles"],
                "headless": ex.get("headless", True), "timeout_ms": ex.get("default_timeout_ms", 15000),
                "trace_on_failure": ex.get("trace_on_failure", True),
                "console_errors_fail": cfg["policy"].get("console_errors_fail", False),
                "accessibility": cfg.get("accessibility", {}), "visual_dir": str(project.root / "visual"),
                "inbox_url": inbox.client_url(cfg) if inbox.needed(project) else None,
                "inbox_wait_s": float(((cfg.get("login") or {}).get("otp") or {}).get("timeout_s", 25)),
                "contacts": {r: {k: str(v) for k, v in (spec or {}).items() if k in ("mobile", "email")}
                             for r, spec in project.roles().items()},
                "apps": {aid: {"base_url": a["base_url"], "login_url": project.login_cfg(aid).get("url") or "/login",
                               "name": a["name"], "production": project.is_production(aid)}
                         for aid, a in project.applications().items()},
                "primary_app": project.primary_app,
                "evidence": ex.get("evidence", "all"), "video": bool(ex.get("video", False)),
                "clock_hook": (cfg.get("functional") or {}).get("clock_hook"),
                "max_wait_s": float((cfg.get("functional") or {}).get("max_wait_s") or 90),
                "language": language.settings(project),
                # how each role's screens authenticate API calls (header name and where its value is kept: never a value)
                "api_auth": store.get_meta("api_auth") or {},
                "landing": _landings(project)}
    (out / "agentqa_settings.json").write_text(json.dumps(settings, indent=2), encoding="utf-8")
    (out / "pytest.ini").write_text("[pytest]\naddopts = -p no:cacheprovider\nmarkers =\n    case: AgentQA case id\n"
                                    "    aq_login: logs in afresh (run last, one at a time)\n", encoding="utf-8")
    files: dict[str, list[str]] = {}
    for c in cases:
        fname = FILES[c["type"]]
        lines = files.setdefault(fname, [HEADER.format(what=WHAT[fname])])
        doc = (f"Rules: {', '.join(c['rule_ids']) or '-'} | Requirements: {', '.join(c['req_ids']) or '-'} | "
               f"Oracle: {c['oracle_source']} | Priority: {c['priority']}")
        lines.append("")
        lines.append("")
        lines.append(f"@pytest.mark.case({c['id']!r})")
        if (c["params"] or {}).get("fresh_login"):
            lines.append("@pytest.mark.aq_login")
        lines.append(f"def test_{c['id'].lower().replace('-', '_')}(as_role):")
        lines.append(f'    """{c["title"]}')
        lines.append("")
        lines.append(f'    {doc}')
        if c["type"] == "functional":
            fp = c["params"] or {}
            lines.append(f'    Module: {fp.get("module")} | Scenario: {fp.get("scenario")}')
            lines.append(f'    Expected: {fp.get("expected")}')
        lines.append('    """')
        for b in (_body_new(c) or _body(c)):
            lines.append("    " + b)
    for fname, lines in files.items():
        (out / fname).write_text("\n".join(lines) + "\n", encoding="utf-8")
        n = sum(1 for ln in lines if ln.startswith("def test_"))
        live.emit("generator", "write", f"Wrote tests/{fname} with {n} test(s)", file=fname, tests=n,
                  preview="\n".join(lines[-12:]))
    return {"cases": len(cases), "files": sorted(files)}
